/* scripts/generate-traceletters-hershey.cjs
   Generates baseline TraceLetters from Hershey single-line fonts.
   Output: src/pages/kids/games/phonics/tracing/traceLetters.hershey.ts
*/
const fs = require("fs");
const path = require("path");
const hershey = require("hersheytext");

// Pass font name as CLI arg, default to hershey_sans_med
const FONT_NAME = process.argv[2] || "hershey_sans_med";

const OUT_FILE = path.join(
  process.cwd(),
  "src/pages/kids/games/phonics/tracing/traceLetters.hershey.ts"
);

const VB = "0 0 100 100";
const ST = 0.02;
const EN = 0.98;

function clamp(n, a, b) {
  return Math.max(a, Math.min(b, n));
}

// Tokenize simple M/L path from hersheytext output
function tokenizePath(d) {
  const re = /([ML])|(-?\d*\.?\d+)/gi;
  const out = [];
  let m;
  while ((m = re.exec(d)) !== null) {
    if (m[1]) out.push(m[1].toUpperCase());
    else out.push(Number(m[2]));
  }
  return out;
}

function extractPoints(tokens) {
  const subpaths = [];
  let i = 0;
  let current = null;

  while (i < tokens.length) {
    const t = tokens[i++];

    if (t === "M" || t === "L") {
      const x = tokens[i++];
      const y = tokens[i++];
      if (typeof x !== "number" || typeof y !== "number") break;

      if (t === "M") {
        if (current && current.length) subpaths.push(current);
        current = [{ x, y }];
      } else {
        if (!current) current = [{ x, y }];
        current.push({ x, y });
      }
    }
  }

  if (current && current.length) subpaths.push(current);
  return subpaths;
}

function boundsOfSubpaths(subpaths) {
  let minX = Infinity, minY = Infinity, maxX = -Infinity, maxY = -Infinity;
  for (const sp of subpaths) {
    for (const p of sp) {
      minX = Math.min(minX, p.x);
      minY = Math.min(minY, p.y);
      maxX = Math.max(maxX, p.x);
      maxY = Math.max(maxY, p.y);
    }
  }
  if (!isFinite(minX)) return null;
  return { minX, minY, maxX, maxY };
}

function lengthOfSubpath(sp) {
  let len = 0;
  for (let i = 1; i < sp.length; i++) {
    const dx = sp[i].x - sp[i - 1].x;
    const dy = sp[i].y - sp[i - 1].y;
    len += Math.sqrt(dx * dx + dy * dy);
  }
  return len;
}

function transformSubpaths(subpaths, margin = 12) {
  const b = boundsOfSubpaths(subpaths);
  if (!b) return { subpaths: [] };

  const w = Math.max(0.0001, b.maxX - b.minX);
  const h = Math.max(0.0001, b.maxY - b.minY);

  const scale = Math.min((100 - margin * 2) / w, (100 - margin * 2) / h);

  const newW = w * scale;
  const newH = h * scale;
  const offX = (100 - newW) / 2;
  const offY = (100 - newH) / 2;

  const mapped = subpaths.map((sp) =>
    sp.map((p) => ({
      x: offX + (p.x - b.minX) * scale,
      y: offY + (p.y - b.minY) * scale,
    }))
  );

  return { subpaths: mapped };
}

function subpathToD(sp) {
  if (!sp.length) return "";
  let d = `M ${sp[0].x.toFixed(2)} ${sp[0].y.toFixed(2)}`;
  for (let i = 1; i < sp.length; i++) {
    d += ` L ${sp[i].x.toFixed(2)} ${sp[i].y.toFixed(2)}`;
  }
  return d;
}

function toTapPoint(sp) {
  const mid = sp[Math.floor(sp.length / 2)] || sp[0];
  return `M ${mid.x.toFixed(2)} ${mid.y.toFixed(2)}`;
}

function makeLetterEntry(ch, caseTag) {
  const font = hershey.getFontData(FONT_NAME);
  const char = font.getChar(ch);
  if (!char || !char.d) return null;

  const tokens = tokenizePath(char.d);
  const rawSubpaths = extractPoints(tokens);
  const { subpaths } = transformSubpaths(rawSubpaths);

  if (!subpaths.length) return null;

  const strokes = subpaths.map((sp, idx) => {
    const approxLen = lengthOfSubpath(sp);

    if (approxLen < 3) {
      return {
        id: `${ch}_tap_${idx + 1}`,
        kind: "tap",
        pathD: toTapPoint(sp),
      };
    }

    return {
      id: `${ch}_stroke_${idx + 1}`,
      kind: "trace",
      startT: ST,
      endT: EN,
      pathD: subpathToD(sp),
    };
  });

  const skillTags = [
    `letter:${ch}`,
    `case:${caseTag}`,
    "subtopic:tracing",
    "source:hersheytext",
    `font:${FONT_NAME}`,
  ];

  return { id: ch, label: ch, viewBox: VB, strokes, skillTags };
}

function generateAll() {
  const out = {};
  const AZ = "ABCDEFGHIJKLMNOPQRSTUVWXYZ";
  const az = "abcdefghijklmnopqrstuvwxyz";

  for (const ch of AZ) {
    const entry = makeLetterEntry(ch, "upper");
    if (entry) out[ch] = entry;
  }
  for (const ch of az) {
    const entry = makeLetterEntry(ch, "lower");
    if (entry) out[ch] = entry;
  }
  return out;
}

const letters = generateAll();

const file = `/* AUTO-GENERATED: Hershey baseline tracing letters
   Font: ${FONT_NAME}
   Generated by: scripts/generate-traceletters-hershey.cjs
*/
import type { TraceLetter, LetterId } from "./traceLetters";

export const HERSHEY_TRACE_LETTERS: Partial<Record<LetterId, TraceLetter>> = ${JSON.stringify(
  letters,
  null,
  2
)};
`;

fs.mkdirSync(path.dirname(OUT_FILE), { recursive: true });
fs.writeFileSync(OUT_FILE, file, "utf8");

console.log("✅ Generated:", OUT_FILE);
console.log("Font used:", FONT_NAME);
console.log("Letters generated:", Object.keys(letters).length);
