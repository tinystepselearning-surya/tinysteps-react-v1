// Shared deterministic core test scenarios. No file or cloud access.
export function registryCases(validate, manifest, shards, previous) {
  const clone=x=>JSON.parse(JSON.stringify(x));
  const entries=Object.keys(shards);
  const run=(m,s,p=previous,reads=[])=>validate(m,path=>{reads.push(path);if(!Object.hasOwn(s,path))throw Error("missing");return s[path]},p);
  const cases=[];
  const check=(name,fn)=>{try{fn();cases.push({name,pass:true})}catch(e){cases.push({name,pass:false,error:String(e.message)})}};
  const assert=(condition,message)=>{if(!condition)throw Error(message)};
  const expect=(name,mutate,code)=>check(name,()=>{
    const m=clone(manifest),s=clone(shards),p=clone(previous),reads=[];
    mutate(m,s,p);
    const r=run(m,s,p,reads);
    assert(!r.structurallyValid&&r.errors.some(e=>e.code===code),code+" absent: "+JSON.stringify(r.errors.slice(0,8)));
    assert(!r.executableReady,"incorrect readiness");
  });
  const edit=(s,path,fn)=>{const j=JSON.parse(s[path].text);fn(j);s[path].text=JSON.stringify(j);};
  const before=JSON.stringify({manifest,shards,previous});
  check("real registry and baseline",()=>{const r=run(manifest,shards);assert(r.structurallyValid,JSON.stringify(r.errors));assert(r.counts.records===129&&r.counts.items===971&&!r.executableReady,"counts/readiness")});
  expect("missing shard",(m,s)=>delete s[entries[0]],"SHARD_READ");
  expect("wrong blob digest",(m,s)=>s[entries[0]].blobSha="0".repeat(40),"SHARD_HASH");
  expect("malformed shard JSON",(m,s)=>s[entries[0]].text="{","SHARD_JSON");
  expect("nonobject shard",(m,s)=>s[entries[0]].text="null","SHARD_SHAPE");
  expect("duplicate path",m=>m.shards.push(clone(m.shards[0])),"DUPLICATE_SHARD");
  check("traversal never dispatched",()=>{const m=clone(manifest);m.shards[0].path="../outside.json";const reads=[];const r=run(m,shards,previous,reads);assert(r.errors.some(e=>e.code==="SHARD_PATH")&&!reads.includes("../outside.json"),"unsafe dispatch")});
  expect("absolute path",m=>m.shards[0].path="/tmp/outside.json","SHARD_PATH");
  expect("invalid manifest version",m=>m.formatVersion=3,"MANIFEST_CONTRACT");
  expect("premature manifest adoption",m=>m.status="adopted","MANIFEST_CONTRACT");
  expect("second editable registry",m=>m.records=[],"MANIFEST_CONTRACT");
  expect("manifest count mismatch",m=>m.counts.items++,"MANIFEST_COUNTS");
  expect("shard version",(_,s)=>edit(s,entries[0],j=>j.registryVersion="0.7"),"SHARD_VERSION_GROUP");
  expect("group owner mismatch",(_,s)=>edit(s,entries[0],j=>j.ownerDomains=["platform"]),"SHARD_OWNER_GROUP");
  expect("duplicate owner group",m=>m.shards[1].ownerDomains.push(m.shards[0].ownerDomains[0]),"DUPLICATE_OWNER_GROUP");
  expect("record membership",m=>m.shards[0].recordCodes.pop(),"SHARD_RECORD_MEMBERSHIP");
  expect("shard item count",m=>m.shards[0].items++,"SHARD_ITEM_COUNT");
  expect("cross-shard duplicate record",(_,s)=>{const a=JSON.parse(s[entries[0]].text).records[0];edit(s,entries[1],j=>j.records.push(a))},"DUPLICATE_RECORD");
  expect("cross-shard duplicate item",(_,s)=>{const a=JSON.parse(s[entries[0]].text).records[0];edit(s,entries[1],j=>j.records.push(a))},"DUPLICATE_ITEM");
  expect("duplicate semantic field",(_,s)=>edit(s,entries[0],j=>j.records[0].items.push({...j.records[0].items[0],itemId:"PER-9999"})),"DUPLICATE");
  expect("wrong owner",(_,s)=>edit(s,entries[0],j=>j.records[0].ownerDomain="platform"),"RECORD_OWNER");
  expect("wrong item owner",(_,s)=>edit(s,entries[0],j=>j.records[0].items[0].ownerDomain="platform"),"ITEM_OWNER");
  expect("invalid item ID",(_,s)=>edit(s,entries[0],j=>j.records[0].items[0].itemId="ABC-1"),"ITEM_ID");
  expect("invalid field type",(_,s)=>edit(s,entries[0],j=>j.records[0].items[0].dataType="any"),"ITEM_SHAPE");
  expect("invalid cardinality",(_,s)=>edit(s,entries[0],j=>j.records[0].items[0].cardinality="many"),"ITEM_SHAPE");
  expect("invalid nullable",(_,s)=>edit(s,entries[0],j=>j.records[0].items[0].nullable="false"),"ITEM_SHAPE");
  expect("unknown shared field set",(_,s)=>edit(s,entries[0],j=>j.records[0].fieldSet="missing"),"SHARED_FIELD_REFERENCE");
  expect("missing enum",(m)=>m.valueSets.splice(m.valueSets.findIndex(v=>v.id==="personKind"),1),"VALUE_SET_REFERENCE");
  expect("duplicate enum",m=>m.valueSets.push(clone(m.valueSets[0])),"DUPLICATE_SET");
  expect("enum with wrong type",(_,s)=>edit(s,entries[0],j=>{j.records[0].items.find(i=>i.valueSet).dataType="string"}),"VALUE_SET_REFERENCE");
  expect("broken polymorphic reference",(_,s)=>edit(s,entries[0],j=>{const i=j.records.flatMap(r=>r.items).find(i=>i.reference?.startsWith("polymorphic:"));i.reference="polymorphic:PER|ZZZ"}),"UNKNOWN_REFERENCE");
  expect("nonreference carries ref",(_,s)=>edit(s,entries[0],j=>j.records[0].items[0].reference="PER"),"REFERENCE_SHAPE");
  expect("premature record adoption",(_,s)=>edit(s,entries[0],j=>j.records[0].lifecycle="adopted"),"PREMATURE_ADOPTION");
  expect("premature item adoption",(_,s)=>edit(s,entries[0],j=>j.records[0].items[0].lifecycle="adopted"),"PREMATURE_ADOPTION");
  expect("prior item change",(_,s)=>edit(s,entries[0],j=>j.records[0].items[0].definition+=" changed"),"PRIOR_ITEM_CHANGED");
  expect("prior item removal",(_,s)=>edit(s,entries[0],j=>j.records[0].items.shift()),"PRIOR_ITEM_CHANGED");
  expect("prior record change",(_,s)=>edit(s,entries[0],j=>j.records[0].name="Changed"),"PRIOR_RECORD_CHANGED");
  expect("prior value set change",m=>m.valueSets[0].codes.push("new"),"PRIOR_VALUE_SET_CHANGED");
  expect("previous snapshot pin changed",m=>m.previousSnapshot.commit="f".repeat(40),"PREVIOUS_PIN");
  expect("previous snapshot hash changed",(m,s,p)=>p.blobSha="f".repeat(40),"PREVIOUS_HASH");
  check("deterministic diagnostics",()=>{const m=clone(manifest);m.shards[0].items++;m.counts.items++;assert(JSON.stringify(run(m,shards))===JSON.stringify(run(m,shards)),"non deterministic")});
  check("no mutation of input objects",()=>assert(before===JSON.stringify({manifest,shards,previous}),"input mutated"));
  return cases;
}
