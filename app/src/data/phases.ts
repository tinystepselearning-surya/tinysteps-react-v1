/**
 * phases.ts
 * Data model for 10-phase phonics journey + Phase 0 prep
 * Each phase contains milestones with status and progress tracking
 */

export type MilestoneStatus = "locked" | "in_progress" | "done";

export type MilestoneKPI = "accuracy" | "streak" | "time" | "attempts";

export interface Milestone {
  id: string; // e.g., "P2-M3"
  title: string; // short label
  desc: string; // 1-line description
  status: MilestoneStatus;
  progress: number; // 0–100
  kpi?: MilestoneKPI[]; // optional KPIs to show
}

export type PhaseID = "P0" | "P1" | "P2" | "P2B" | "P3" | "P3B" | "P4" | "P5" | "P6" | "P7" | "P8" | "P9" | "P10";

export interface Phase {
  id: PhaseID;
  name: string;
  age: string;
  color: string; // Tailwind class or hex
  tagline: string;
  milestones: Milestone[];
}

